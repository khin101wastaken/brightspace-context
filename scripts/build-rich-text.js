import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';

const files=[];
files.push(['extension/LICENSE',await readFile('LICENSE','utf8')]);
for(const name of ['rich-text','document-formats']) {
  const result=await build({entryPoints:[`assets/${name}.js`],outfile:`extension/${name}.js`,write:false,bundle:true,format:'esm',platform:'browser',target:'chrome116',minify:false,legalComments:'inline',banner:{js:`// Generated by npm run build:rich-text from assets/${name}.js. Do not edit.`}});
  files.push([`extension/${name}.js`,result.outputFiles[0].text]);
}
const licenses=await Promise.all(['htmlparser2','entities','fflate'].map(async name=>`${name}\n${await readFile(`node_modules/${name}/LICENSE`,'utf8')}`));
files.push(['extension/THIRD-PARTY-LICENSES.txt',licenses.join('\n\n').replace(/[ \t]+$/gm,'')]);
for(const [filename,contents] of files) {
  if(process.argv.includes('--check')) {
    if((await readFile(filename,'utf8')).replace(/\r\n/g,'\n')!==contents.replace(/\r\n/g,'\n')) throw new Error(`Stale generated file: ${filename}. Run npm run build:rich-text.`);
  } else await writeFile(filename,contents);
}
console.log(process.argv.includes('--check')?'Local browser bundles match their sources.':'Bundled HTML parser, document validation and licenses.');
